#!/usr/bin/env python3
"""gen_field_index.py -- FFI::Struct#[] / #[]= over the view fields.

The gem's structs are FFI::Structs, so gem code indexes them
(`model[:materials]`, `node[:position]`, `mesh[:vertexCount] = 1`). Our views
have named accessors; this emits the same index protocol on top of them, as an
explicit `case` per class (AOT-safe: no dynamic symbol dispatch).

Fields come from the `native_method` declarations in raylib_ffi.rb and
raylib_handles_ffi.rb; a field is writable through []= when a `:<name>=`
declaration exists for it.

Rewrites lib/raylib_field_index.rb. Run from the repo root:
    python3 tools/gen_field_index.py
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(ROOT, "lib")
OUT = os.path.join(LIB, "raylib_field_index.rb")

STRUCT_RE = re.compile(r'\s*native_struct "(\w+)"')
GET_RE = re.compile(r'\s*native_method :(\w+), \[\], (:\w+), "[\w]+"')
SET_RE = re.compile(r'\s*native_method :(\w+)=, \[[^\]]*\], (:\w+), "[\w]+"')


def scan(path):
    """{class: {"get": {field: token}, "set": {field: token}}} in file order."""
    out, cur = {}, None
    for line in open(path):
        m = STRUCT_RE.match(line)
        if m:
            cur = m.group(1)
            out.setdefault(cur, {"get": {}, "set": {}})
            continue
        if cur is None:
            continue
        m = GET_RE.match(line)
        if m:
            out[cur]["get"][m.group(1)] = m.group(2)
            continue
        m = SET_RE.match(line)
        if m:
            out[cur]["set"][m.group(1)] = m.group(2)
    return out


def main():
    classes = {}
    for fname in ("raylib_ffi.rb", "raylib_handles_ffi.rb"):
        for cls, fields in scan(os.path.join(LIB, fname)).items():
            merged = classes.setdefault(cls, {"get": {}, "set": {}})
            merged["get"].update(fields["get"])
            merged["set"].update(fields["set"])

    out = ["# frozen_string_literal: true", "",
           "# raylib_field_index.rb -- generated by tools/gen_field_index.py.",
           "#",
           "# FFI::Struct#[] / #[]= over the named accessors, so gem code that",
           "# indexes structs (model[:materials], node[:position],",
           "# mesh[:vertexCount] = 1) works on our views. Expanded per class on",
           "# purpose: a dynamic send() would widen every dispatch under AOT.",
           ""]
    total_get = total_set = 0
    for cls in sorted(classes):
        fields = classes[cls]
        if not fields["get"]:
            continue
        out.append("module Raylib")
        out.append("  class %s" % cls)
        out.append("    def [](key)")
        out.append("      case key")
        for name in fields["get"]:
            out.append("      when :%s then %s" % (name, name))
            total_get += 1
        out.append('      else raise KeyError, "no such field: #{key}"')
        out.append("      end")
        out.append("    end")
        out.append("")
        out.append("    def []=(key, value)")
        if fields["set"]:
            out.append("      case key")
            for name in fields["set"]:
                out.append("      when :%s then self.%s = value" % (name, name))
                total_set += 1
            out.append('      else raise KeyError, "no writable field: #{key}"')
            out.append("      end")
        else:
            out.append('      raise KeyError, "no writable field: #{key}"')
        out.append("    end")
        out.append("  end")
        out.append("end")
        out.append("")
    open(OUT, "w").write("\n".join(out).rstrip("\n") + "\n")
    print("wrote %s: %d classes, %d readable, %d writable fields"
          % (OUT, sum(1 for c in classes if classes[c]["get"]), total_get, total_set))


if __name__ == "__main__":
    sys.exit(main())
